
import { useState } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import {
  Bot,
  Check,
  Copy,
  Sparkles,
} from "lucide-react";

import "./ai-message.css";

type AIMessageProps = {
  content: string;
};

export default function AIMessage({
  content,
}: AIMessageProps) {
  const [copied, setCopied] = useState(false);

  async function handleCopy() {
    try {
      await navigator.clipboard.writeText(content);
      setCopied(true);

      window.setTimeout(() => {
        setCopied(false);
      }, 2000);
    } catch {
      setCopied(false);
    }
  }

  return (
    <article className="pp-ai-message">
      <header className="pp-ai-message-header">
        <div className="pp-ai-identity">
          <div className="pp-ai-avatar">
            <Bot size={21} />
          </div>

          <div className="pp-ai-identity-text">
            <strong>PharmaPilot AI</strong>
            <span>Intelligent Assistant</span>
          </div>
        </div>

        <span className="pp-ai-response-badge">
          <Sparkles size={13} />
          AI Response
        </span>
      </header>

      <div className="pp-ai-message-body">
        <ReactMarkdown
          remarkPlugins={[remarkGfm]}
          components={{
            a: ({ children, href }) => (
              <a
                href={href}
                target="_blank"
                rel="noopener noreferrer"
              >
                {children}
              </a>
            ),

            table: ({ children }) => (
              <div className="pp-ai-table-scroll">
                <table>{children}</table>
              </div>
            ),

            code: ({ children, className }) => {
              return (
                <code className={className}>
                  {children}
                </code>
              );
            },
          }}
        >
          {content}
        </ReactMarkdown>
      </div>

      <footer className="pp-ai-message-footer">
        <span className="pp-ai-footer-label">
          <Sparkles size={13} />
          Generated by PharmaPilot
        </span>

        <button
          type="button"
          className="pp-ai-copy-button"
          onClick={() => void handleCopy()}
          aria-label="Copy AI response"
        >
          {copied ? (
            <>
              <Check size={15} />
              Copied
            </>
          ) : (
            <>
              <Copy size={15} />
              Copy response
            </>
          )}
        </button>
      </footer>
    </article>
  );
}
